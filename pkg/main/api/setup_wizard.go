func wizardSaveIndexerStep(c *gin.Context) (alert, name string) {
	nm := strings.TrimSpace(c.PostForm("wizard_indexer_Name"))
	rawURL := strings.TrimSpace(c.PostForm("wizard_indexer_URL"))
	apikey := strings.TrimSpace(c.PostForm("wizard_indexer_Apikey"))
	indexerType := c.PostForm("wizard_indexer_IndexerType")

	if rawURL == "" {
		return "", ""
	}

	if nm == "" {
		nm = "MyIndexer"
	}

	// The searcher only queries IndexerType "newznab"; the newznab provider
	// serves Torznab too and detects it from the URL, so torznab is stored as
	// newznab rather than producing an indexer that is never searched.
	if indexerType == "" || strings.EqualFold(indexerType, "torznab") {
		indexerType = "newznab"
	}

	// The limits as entered; 5 per 20 s when left empty.
	atoi := func(field string, def int) int {
		if n, err := strconv.Atoi(strings.TrimSpace(c.PostForm("wizard_indexer_" + field))); err == nil && n >= 0 {
			return n
		}

		return def
	}

	cfg := config.IndexersConfig{
		Name:              nm,
		IndexerType:       indexerType,
		URL:               rawURL,
		Apikey:            apikey,
		Enabled:           true,
		Limitercalls:      max(atoi("Limitercalls", 5), 1),
		Limiterseconds:    uint8(min(max(atoi("Limiterseconds", 20), 1), 255)),
		LimitercallsDaily: atoi("LimitercallsDaily", 0),
		MaxEntries:        100,
		RssEntriesloop:    2,
	}

	if err := config.UpdateCfgEntry(config.Conf{Name: "indexer_" + nm, Data: cfg}); err != nil {
		return renderAlert("Failed to save indexer: "+err.Error(), "danger"), ""
	}

	providers.ReloadClientProviders()

	return renderAlert("Indexer '"+nm+"' saved.", "success"), nm
}

