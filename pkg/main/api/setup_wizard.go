// wizardConfigLooksDefault reports whether every section ClearCfg seeds is
// still exactly its untouched placeholder ("initial"/empty) - i.e. the config
// was generated by ClearCfg and nobody has configured anything since.
func wizardConfigLooksDefault() bool {
	isInitialOnly := func(names []string) bool {
		return len(names) == 1 && names[0] == "initial"
	}

	downloaders := wizardNames(
		config.GetSettingsDownloaderAll(),
		func(d config.DownloaderConfig) string { return d.Name },
	)
	indexers := wizardNames(
		config.GetSettingsIndexerAll(),
		func(i config.IndexersConfig) string { return i.Name },
	)
	paths := wizardNames(config.GetSettingsPathAll(), func(p config.PathsConfig) string { return p.Name })
	lists := wizardNames(config.GetSettingsListAll(), func(l config.ListsConfig) string { return l.Name })

	if !isInitialOnly(downloaders) || !isInitialOnly(indexers) || !isInitialOnly(paths) ||
		!isInitialOnly(lists) {
		return false
	}

	media := config.GetSettingsMediaAll()
	if media == nil {
		return false
	}

	movies := wizardNames(media.Movies, func(m config.MediaTypeConfig) string { return m.Name })
	series := wizardNames(media.Series, func(m config.MediaTypeConfig) string { return m.Name })

	if !isInitialOnly(movies) || !isInitialOnly(series) {
		return false
	}

	return len(media.Books) == 0 && len(media.AudioBooks) == 0 && len(media.Music) == 0
}

// HandleWizardDismiss marks the current session as having seen the wizard so
// the dashboard stops auto-redirecting to it, then sends the user on to the
// dashboard.
func HandleWizardDismiss(c *gin.Context) {
	if sessionCookie, err := c.Cookie("session_id"); err == nil {
		sessionStore.markWizardDismissed(sessionCookie)
	}

	c.Redirect(http.StatusFound, "/api/admin")
}

// ---- Routing handlers ----

// HandleWizardStepGet renders a step fragment with fresh data - used both for
// forward navigation and for reloading a step.
func HandleWizardStepGet(c *gin.Context) {
	n := wizardParseStep(c.Param("n"))
	state := readWizardState(c)
	csrfToken := getCSRFToken(c)

	c.Header("Content-Type", "text/html")
	c.String(http.StatusOK, renderComponentToString(renderWizardFragment(n, csrfToken, state)))
}

// HandleWizardStepSave saves step n's own contribution and returns the
// rendered fragment for step n+1. Steps 5 (Lists) has no case here - it saves
// via the embedded Settings section's own endpoint instead.
func HandleWizardStepSave(c *gin.Context) {
	if err := c.Request.ParseForm(); err != nil {
		c.Header("Content-Type", "text/html")
		c.String(http.StatusOK, renderAlert("Failed to parse form data: "+err.Error(), "danger"))

		return
	}

	n := wizardParseStep(c.Param("n"))
	state := readWizardState(c)
	csrfToken := getCSRFToken(c)

	var alert string

	switch n {
	case 1:
		alert, state.Groups = wizardSaveGroupsStep(c, state)
	case 2:
		alert, state.Groups = wizardSavePathsStep(c, state)
	case 3:
		var name string

		alert, name = wizardSaveIndexerStep(c)
		if name != "" {
			state.Indexer = name
		}
	case 4:
		var name string

		alert, name = wizardSaveDownloaderStep(c)
		if name != "" {
			state.Downloader = name
		}
	case 6:
		alert = wizardSaveFinalizeStep(c, state)
	}

	next := n + 1
	if next > wizardLastStep {
		next = wizardLastStep
	}

	c.Header("Content-Type", "text/html")
	c.String(http.StatusOK, alert+renderComponentToString(renderWizardFragment(next, csrfToken, state)))
}

func wizardParseStep(raw string) int {
	n, err := strconv.Atoi(raw)
	if err != nil || n < 1 || n > wizardLastStep {
		return 1
	}

	return n
}

// wizardFormOrQuery reads a value posted as form data (Save) or as a query
// string parameter (Skip/Continue, which htmx sends as a plain GET with
// included values serialized into the URL).
func wizardFormOrQuery(c *gin.Context, key string) string {
	if v := c.PostForm(key); v != "" {
		return v
	}

	return c.Query(key)
}

func readWizardState(c *gin.Context) wizardState {
	state := wizardState{
		Indexer:    wizardFormOrQuery(c, "wizard_ctx_indexer"),
		Downloader: wizardFormOrQuery(c, "wizard_ctx_downloader"),
		Groups:     make(map[string]wizardGroupState, len(wizardMediaGroupDefs)),
	}

	for _, d := range wizardMediaGroupDefs {
		g := wizardGroupState{
			Enabled:     wizardFormOrQuery(c, "wizard_ctx_group_"+d.key+"_enabled") != "",
			Name:        wizardFormOrQuery(c, "wizard_ctx_group_"+d.key+"_name"),
			LibraryPath: wizardFormOrQuery(c, "wizard_ctx_group_"+d.key+"_library"),
			ImportPath:  wizardFormOrQuery(c, "wizard_ctx_group_"+d.key+"_import"),
		}
		if g.Enabled || g.Name != "" || g.LibraryPath != "" || g.ImportPath != "" {
			state.Groups[d.key] = g
		}
	}

	return state
}

func wizardHiddenState(state wizardState) gomponents.Node {
	nodes := []gomponents.Node{
		html.Input(html.Type("hidden"), html.Name("wizard_ctx_indexer"), html.Value(state.Indexer)),
		html.Input(
			html.Type("hidden"),
			html.Name("wizard_ctx_downloader"),
			html.Value(state.Downloader),
		),
	}

	for _, d := range wizardMediaGroupDefs {
		g := state.Groups[d.key]

		enabled := ""
		if g.Enabled {
			enabled = "1"
		}

		nodes = append(nodes,
			html.Input(
				html.Type("hidden"),
				html.Name("wizard_ctx_group_"+d.key+"_enabled"),
				html.Value(enabled),
			),
			html.Input(
				html.Type("hidden"),
				html.Name("wizard_ctx_group_"+d.key+"_name"),
				html.Value(g.Name),
			),
			html.Input(
				html.Type("hidden"),
				html.Name("wizard_ctx_group_"+d.key+"_library"),
				html.Value(g.LibraryPath),
			),
			html.Input(
				html.Type("hidden"),
				html.Name("wizard_ctx_group_"+d.key+"_import"),
				html.Value(g.ImportPath),
			),
		)
	}

	return gomponents.Group(nodes)
}

// ---- Fragment dispatch ----

func renderWizardFragment(step int, csrfToken string, state wizardState) gomponents.Node {
	var body gomponents.Node

	switch step {
	case 1:
		body = renderWizardStepGroups(csrfToken, state)
	case 2:
		body = renderWizardStepPaths(csrfToken, state)
	case 3:
		body = renderWizardStepIndexer(csrfToken)
	case 4:
		body = renderWizardStepDownloader(csrfToken)
	case 5:
		body = renderWizardStepLists(csrfToken)
	case 6:
		body = renderWizardStepFinalize(csrfToken, state)
	default:
		body = renderWizardStepFinish()
	}

	// wizardCarry holds the hidden state fields outside any particular step's
	// own <form>, so every nav/save button (whose hx-include lists this div)
	// keeps forwarding the accumulated selections regardless of whether the
	// current step has its own form (step 5 doesn't).
	return html.Div(
		wizardProgressBar(step),
		html.Div(html.ID("wizardCarry"), wizardHiddenState(state)),
		body,
	)
}

func wizardProgressBar(active int) gomponents.Node {
	items := make([]gomponents.Node, 0, len(wizardStepLabels))

	for i, label := range wizardStepLabels {
		n := i + 1
		class := "badge rounded-pill bg-secondary me-2 mb-2"

		switch {
		case n == active:
			class = "badge rounded-pill bg-primary me-2 mb-2"
		case n < active:
			class = "badge rounded-pill bg-success me-2 mb-2"
		}

		items = append(
			items,
			html.Span(html.Class(class), gomponents.Text(fmt.Sprintf("%d. %s", n, label))),
		)
	}

	return html.Div(html.Class("mb-3"), gomponents.Group(items))
}

