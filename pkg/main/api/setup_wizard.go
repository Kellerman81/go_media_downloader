func wizardSavePathsStep(
	c *gin.Context,
	state wizardState,
) (alert string, groups map[string]wizardGroupState) {
	groups = state.Groups
	if groups == nil {
		groups = map[string]wizardGroupState{}
	}

	var folders []wizardFolder

	for _, d := range wizardEnabledGroups(state) {
		name := groups[d.key].Name
		folders = append(folders,
			wizardFolder{group: name, kind: "library", path: strings.TrimSpace(c.PostForm("wizard_path_Library" + d.label))},
			wizardFolder{group: name, kind: "import", path: strings.TrimSpace(c.PostForm("wizard_path_Import" + d.label))})
	}

	if problems := wizardCheckFolders(folders, c.PostForm("wizard_path_create") != ""); len(problems) > 0 {
		return renderAlert("Nothing was saved, please correct: "+strings.Join(problems, "; "), "danger"), groups
	}

	var created, failed []string

	for _, d := range wizardEnabledGroups(state) {
		g := groups[d.key]

		if lib := strings.TrimSpace(c.PostForm("wizard_path_Library" + d.label)); lib != "" {
			cfg := config.PathsConfig{Name: g.Name + "-Library", Path: lib}
			wizardApplyExtensions(&cfg, d.qualityKind)

			if err := config.UpdateCfgEntry(config.Conf{Name: "path_" + cfg.Name, Data: cfg}); err != nil {
				failed = append(failed, cfg.Name+": "+err.Error())
			} else {
				g.LibraryPath = cfg.Name
				created = append(created, cfg.Name)
			}
		}

		if imp := strings.TrimSpace(c.PostForm("wizard_path_Import" + d.label)); imp != "" {
			cfg := config.PathsConfig{Name: g.Name + "-Import", Path: imp}
			wizardApplyExtensions(&cfg, d.qualityKind)

			if err := config.UpdateCfgEntry(config.Conf{Name: "path_" + cfg.Name, Data: cfg}); err != nil {
				failed = append(failed, cfg.Name+": "+err.Error())
			} else {
				g.ImportPath = cfg.Name
				created = append(created, cfg.Name)
			}
		}

		groups[d.key] = g
	}

	if len(failed) > 0 {
		return renderAlert("Failed to save path(s): "+strings.Join(failed, "; "), "danger"), groups
	}

	if len(created) == 0 {
		return "", groups
	}

	return renderAlert("Path(s) saved: "+strings.Join(created, ", "), "success"), groups
}

