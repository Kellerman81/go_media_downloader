// wizardNames extracts Name-like fields via the given accessor.
func wizardNames[T any](items []T, name func(T) string) []string {
	out := make([]string, 0, len(items))
	for _, it := range items {
		out = append(out, name(it))
	}

	return out
}

func wizardNameExists(names []string, want string) bool {
	for _, n := range names {
		if n == want {
			return true
		}
	}

	return false
}

// wizardNonEmpty filters out blank entries (a selectarray with nothing chosen
// can still post a single empty-string value).
func wizardNonEmpty(values []string) []string {
	out := make([]string, 0, len(values))

	for _, v := range values {
		if v != "" {
			out = append(out, v)
		}
	}

	return out
}

