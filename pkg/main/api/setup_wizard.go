func wizardEnabledGroups(state wizardState) []wizardMediaGroupDef {
	out := make([]wizardMediaGroupDef, 0, len(wizardMediaGroupDefs))

	for _, d := range wizardMediaGroupDefs {
		if state.Groups[d.key].Enabled {
			out = append(out, d)
		}
	}

	return out
}

// wizardApplyExtensions sets the allowed-extension fields on cfg based on a
// group's media kind, so the Paths step never has to ask the user to pick
// extensions manually.
func wizardApplyExtensions(cfg *config.PathsConfig, kind string) {
	switch kind {
	case "video":
		cfg.AllowedVideoExtensions = []string{".mkv", ".mp4", ".avi", ".m4v"}
		cfg.AllowedOtherExtensions = []string{".srt", ".nfo", ".idx", ".sub"}
	case "music", "audiobook":
		cfg.AllowedAudioExtensions = []string{".mp3", ".flac", ".m4a", ".m4b", ".ogg", ".opus"}
	case "book":
		cfg.AllowedBookExtensions = []string{".epub", ".pdf", ".mobi", ".azw3"}
	}
}

func wizardExtensionHint(kind string) string {
	switch kind {
	case "video":
		return "video files (.mkv/.mp4/.avi) plus subtitles/nfo"
	case "music":
		return "audio files (.mp3/.flac/.m4a/.ogg/.opus)"
	case "audiobook":
		return "audiobook files (.mp3/.m4b/.flac)"
	case "book":
		return "ebook files (.epub/.pdf/.mobi/.azw3)"
	default:
		return "files"
	}
}

// wizardConflicts lists the config entries the finalize step would overwrite
// for the given groups: an existing media group of the same name (its data,
// import, notification and list settings would be lost) or an existing
// "<name>-Quality" / "<name>-Regex" profile.
func wizardConflicts(mc *config.MediaConfig, groups []wizardMediaGroupDef, state wizardState) []string {
	regexNames := wizardNames(config.GetSettingsRegexAll(), func(r config.RegexConfig) string { return r.Name })
	schedulerNames := wizardNames(config.GetSettingsSchedulerAll(), func(s config.SchedulerConfig) string { return s.Name })

	var conflicts []string

	for _, d := range groups {
		name := state.Groups[d.key].Name

		for _, existing := range *d.target(mc) {
			if strings.EqualFold(existing.Name, name) {
				conflicts = append(conflicts, d.label+" media group \""+name+"\"")
				break
			}
		}

		if _, ok := config.GetSettingsQualityOk(name + "-Quality"); ok {
			conflicts = append(conflicts, "quality profile \""+name+"-Quality\"")
		}

		if wizardNameExists(regexNames, name+"-Regex") {
			conflicts = append(conflicts, "regex profile \""+name+"-Regex\"")
		}

		if wizardNameExists(schedulerNames, name+"-Schedule") {
			conflicts = append(conflicts, "schedule \""+name+"-Schedule\"")
		}
	}

	return conflicts
}

// ---- Media groups step (selection only - no config.toml writes yet) ----

func renderWizardStepGroups(csrfToken string, state wizardState) gomponents.Node {
	rows := make([]gomponents.Node, 0, len(wizardMediaGroupDefs))

	for _, d := range wizardMediaGroupDefs {
		g := state.Groups[d.key]

		nameDefault := d.defaultName
		if g.Name != "" {
			nameDefault = g.Name
		}

		rows = append(rows, html.Div(
			html.Class("col-md-6 col-lg-4 mb-3"),
			renderFormGroup(
				"wizard_group",
				map[string]string{d.enabledField: "Create a " + d.label + " media group"},
				map[string]string{d.enabledField: "Enable " + d.label},
				d.enabledField, "checkbox", g.Enabled, nil,
			),
			renderFormGroup(
				"wizard_group",
				map[string]string{d.nameField: "Group name"},
				map[string]string{d.nameField: d.label + " Group Name"},
				d.nameField, "text", nameDefault, nil,
			),
		))
	}

	return html.Div(
		html.Class("config-section-enhanced"),
		renderEnhancedPageHeader(
			"fa-solid fa-layer-group",
			fmt.Sprintf("Step %d: Media Groups", wizStepGroups),
			"Pick which media types this instance should manage. This decides what the next steps ask for - e.g. how many storage paths to create and which file extensions they should accept.",
		),
		html.Form(
			html.Class("config-form"),
			html.ID("wizardStepForm"),
			html.Div(html.Class("row"), gomponents.Group(rows)),
			html.Div(
				html.Class("form-group submit-group mt-3"),
				wizardSaveButton(wizStepGroups, csrfToken),
				wizardNextButton(wizStepGroups, "Skip"),
			),
		),
	)
}

func wizardSaveGroupsStep(
	c *gin.Context,
	state wizardState,
) (alert string, groups map[string]wizardGroupState) {
	groups = make(map[string]wizardGroupState, len(wizardMediaGroupDefs))

	var enabledNames []string

	for _, d := range wizardMediaGroupDefs {
		prev := state.Groups[d.key]

		g := wizardGroupState{
			Enabled:     c.PostForm("wizard_group_"+d.enabledField) != "",
			Name:        strings.TrimSpace(c.PostForm("wizard_group_" + d.nameField)),
			LibraryPath: prev.LibraryPath,
			ImportPath:  prev.ImportPath,
		}
		if g.Name == "" {
			g.Name = d.defaultName
		}

		if g.Enabled {
			enabledNames = append(enabledNames, g.Name)
		}

		groups[d.key] = g
	}

	if len(enabledNames) == 0 {
		return "", groups
	}

	return renderAlert("Selected: "+strings.Join(enabledNames, ", "), "success"), groups
}

// ---- Storage paths step (templated per group selected in the first step) ----

