const (
	wizardTestTimeout = 10 * time.Second
	wizardDefaultName = "Wizard-Default"
	wizardLastStep    = 7
)

var wizardStepLabels = []string{
	"Media Groups",
	"Storage Paths",
	"Indexer",
	"Download Client",
	"Lists",
	"Finalize",
	"Finish",
}

// wizardGroupState is what step 1 (selection) and step 2 (paths) accumulate
// per media group before step 6 (finalize) turns it into a real
// MediaTypeConfig.
type wizardGroupState struct {
	Enabled     bool
	Name        string
	LibraryPath string // PathsConfig.Name for the group's Data path
	ImportPath  string // PathsConfig.Name for the group's DataImport path
}

// wizardState carries what earlier steps decided across requests via hidden
// form fields - there is no server-side wizard session.
type wizardState struct {
	Indexer    string
	Downloader string
	Groups     map[string]wizardGroupState // keyed by wizardMediaGroupDef.key
}

